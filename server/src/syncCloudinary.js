export async function syncAllProducts() {
  console.log('Connecting to MongoDB Atlas...');
  await connectDB();

  console.log(`Synchronizing all ${ALL_57_PRODUCTS.length} Cloudinary video products to Atlas...`);

  let added = 0;
  let updated = 0;

  for (const item of ALL_57_PRODUCTS) {
    const existing = await Product.findOne({ slug: item.slug });
    if (existing) {
      await Product.updateOne({ slug: item.slug }, { $set: item });
      updated++;
    } else {
      await Product.create(item);
      added++;
    }
  }

  console.log(`✅ Synchronization Complete: ${added} new products added, ${updated} products updated.`);

  // Also sync to legacy Video collection
  console.log('Syncing to legacy Video collection...');
  for (const p of ALL_57_PRODUCTS) {
    const legacyCategory = p.category === 'Royal Traditional' ? 'Royal Palace' : p.category === '3D AI Invitation' ? 'Royal Palace' : p.category === 'Caricature & Save The Date' ? 'Animated Caricature' : p.category === 'Minimal & Modern' ? 'Modern Minimalist' : p.category === 'South Indian' ? 'Traditional Vedic' : 'Royal Palace';
    const legacyDoc = {
      title: p.title,
      slug: p.slug,
      description: p.description,
      category: legacyCategory,
      price: p.price,
      originalPrice: p.originalPrice,
      durationSeconds: p.durationSeconds,
      aspectRatio: '9:16',
      previewVideoUrl: p.previewVideo,
      thumbnailUrl: p.thumbnail,
      tags: p.tags,
      features: p.features,
      isFeatured: ['Bestseller', 'Trending'].includes(p.badge),
      deliveryHours: p.deliveryHours,
      rating: p.rating,
      reviewsCount: p.numReviews,
    };

    const exVideo = await Video.findOne({ slug: p.slug });
    if (exVideo) {
      await Video.updateOne({ slug: p.slug }, { $set: legacyDoc });
    } else {
      await Video.create(legacyDoc);
    }
  }

  const finalCount = await Product.countDocuments();
  console.log(`🎉 Total active products in MongoDB Atlas: ${finalCount}`);
  process.exit(0);
}

// Run if called directly
if (process.argv[1]?.endsWith('syncCloudinary.js')) {
  syncAllProducts().catch((err) => {
    console.error('Sync failed:', err);
    process.exit(1);
  });
}
